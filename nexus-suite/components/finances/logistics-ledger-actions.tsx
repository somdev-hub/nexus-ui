'use client';

import { useState } from 'react';
import { Button } from '@/components/ui/button';
import {
    Dialog,
    DialogContent,
    DialogDescription,
    DialogHeader,
    DialogTitle,
} from '@/components/ui/dialog';
import { Download, Eye } from 'lucide-react';
import type { FinanceTxn } from '@/types/finances';

// ─────────────────────────────────────────────────────────────
// Ledger row actions for the logistics finances page: details
// dialog + downloadable invoice/record per transaction kind
// (freight invoice, carrier payable, settlement line).
// ─────────────────────────────────────────────────────────────

function fmtRaw(amount: number | null | undefined, currency?: string | null) {
    if (amount === null || amount === undefined) return '—';
    return `${currency ?? ''} ${Number(amount).toLocaleString(undefined, {
        minimumFractionDigits: 2,
    })}`.trim();
}

function dt(v?: string | number | Date | null) {
    return v ? new Date(v).toLocaleString() : '—';
}

function kindLabel(kind: string) {
    switch (kind) {
        case 'FREIGHT':
            return 'Freight invoice';
        case 'CARRIER_PAYABLE':
            return 'Carrier payable';
        case 'SETTLEMENT_BASE_TRIP':
            return 'Settlement · trip fare';
        case 'SETTLEMENT_LATE_FEE':
            return 'Settlement · late fee';
        case 'SETTLEMENT_CYCLE_PENALTY':
            return 'Settlement · cycle penalty';
        default:
            return kind;
    }
}

function detailRow(k: string, v?: string | number | null, mono = false) {
    return (
        <div
            key={k}
            className="grid grid-cols-[130px_minmax(0,1fr)] items-start gap-2 py-1 text-sm"
        >
            <span className="text-muted-foreground">{k}</span>
            <span
                className={`min-w-0 break-all font-medium ${mono ? 'font-mono text-xs' : ''}`}
            >
                {v ?? '—'}
            </span>
        </div>
    );
}

/** Builds the downloadable txt record for a ledger row. */
function buildInvoiceText(row: FinanceTxn): string {
    const c = row.currency ?? '';
    const title =
        row.kind === 'FREIGHT'
            ? 'NEXUS — FREIGHT INVOICE'
            : row.kind === 'CARRIER_PAYABLE'
              ? 'NEXUS — CARRIER PAYABLE'
              : 'NEXUS — LOGISTICS SETTLEMENT LINE';
    const lines: string[] = [
        title,
        '='.repeat(title.length),
        `${'Number'.padEnd(16, ' ')}: ${row.number ?? row.id}`,
        `${'Document'.padEnd(16, ' ')}: ${kindLabel(row.kind)}`,
        `${'Status'.padEnd(16, ' ')}: ${row.status}`,
        `${'Party'.padEnd(16, ' ')}: ${row.party ?? '—'}`,
        `${'Amount'.padEnd(16, ' ')}: ${fmtRaw(row.amount, c)}`,
        `${'Issued'.padEnd(16, ' ')}: ${dt(row.date)}`,
        `${'Due'.padEnd(16, ' ')}: ${dt(row.dueDate)}`,
        `${'Paid at'.padEnd(16, ' ')}: ${dt(row.paidAt)}`,
    ];
    if (row.shipmentId || row.shipmentNumber) {
        lines.push(
            '',
            `${'Shipment'.padEnd(16, ' ')}: ${row.shipmentNumber ?? row.shipmentId ?? '—'}`
        );
        if (row.lane) lines.push(`${'Lane'.padEnd(16, ' ')}: ${row.lane}`);
    }
    if (row.kind === 'FREIGHT') {
        lines.push(
            '',
            '--- Fare breakdown ---',
            `${'Freight cost'.padEnd(16, ' ')}: ${fmtRaw(row.freightCost, c)}`,
            `${'Fuel surcharge'.padEnd(16, ' ')}: ${fmtRaw(row.fuelSurcharge, c)}`,
            `${'Accessorial'.padEnd(16, ' ')}: ${fmtRaw(row.accessorialCharges, c)}`,
            `${'Tax'.padEnd(16, ' ')}: ${fmtRaw(row.taxAmount, c)}`,
            `${'Total'.padEnd(16, ' ')}: ${fmtRaw(row.amount, c)}`
        );
        if (row.pmsStatus)
            lines.push(`${'PMS status'.padEnd(16, ' ')}: ${row.pmsStatus}`);
    }
    if (row.kind === 'CARRIER_PAYABLE') {
        lines.push(
            '',
            `${'Paid'.padEnd(16, ' ')}: ${fmtRaw(row.paidAmount, c)}`,
            `${'Outstanding'.padEnd(16, ' ')}: ${fmtRaw(Number(row.amount ?? 0) - Number(row.paidAmount ?? 0), c)}`
        );
        if (row.pmsReferenceId)
            lines.push(
                `${'PMS reference'.padEnd(16, ' ')}: ${row.pmsReferenceId}`
            );
    }
    if (row.kind === 'SETTLEMENT_BASE_TRIP') {
        lines.push(
            '',
            `${'Paid'.padEnd(16, ' ')}: ${fmtRaw(row.paidAmount, c)}`,
            `${'Outstanding'.padEnd(16, ' ')}: ${fmtRaw(Number(row.amount ?? 0) - Number(row.paidAmount ?? 0), c)}`
        );
    }
    if (row.partnershipId)
        lines.push(`${'Partnership'.padEnd(16, ' ')}: ${row.partnershipId}`);
    if (row.notes) lines.push('', `Notes: ${row.notes}`);
    lines.push('', 'Generated by Nexus Suite.');
    return lines.join('\n');
}

export function LogisticsLedgerActions({ row }: { row: FinanceTxn }) {
    const [open, setOpen] = useState(false);
    const isFreight = row.kind === 'FREIGHT';
    const isPayable = row.kind === 'CARRIER_PAYABLE';
    const isSettlement = row.kind.startsWith('SETTLEMENT_');
    const outstanding = Number(row.amount ?? 0) - Number(row.paidAmount ?? 0);

    const download = () => {
        const blob = new Blob([buildInvoiceText(row)], {
            type: 'text/plain',
        });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `${row.number ?? row.id}-${row.kind.toLowerCase()}.txt`;
        document.body.appendChild(a);
        a.click();
        a.remove();
        URL.revokeObjectURL(url);
    };

    return (
        <>
            <div className="flex justify-end gap-1">
                <Button size="sm" variant="ghost" onClick={() => setOpen(true)}>
                    <Eye className="mr-1 h-4 w-4" />
                    Details
                </Button>
                <Button size="sm" variant="outline" onClick={download}>
                    <Download className="mr-1 h-4 w-4" />
                    Invoice
                </Button>
            </div>

            <Dialog open={open} onOpenChange={setOpen}>
                <DialogContent className="slim-scrollbar max-h-[85vh] overflow-y-auto md:max-w-lg">
                    <DialogHeader>
                        <DialogTitle>{kindLabel(row.kind)}</DialogTitle>
                        <DialogDescription>
                            {row.number ?? `#${row.id}`}
                        </DialogDescription>
                    </DialogHeader>

                    <div>
                        {detailRow('Status', row.status)}
                        <div className="grid grid-cols-[130px_minmax(0,1fr)] items-start gap-2 py-1 text-sm">
                            <span className="text-muted-foreground">
                                Amount
                            </span>
                            <span className="min-w-0 font-mono font-medium">
                                {fmtRaw(row.amount, row.currency)}
                            </span>
                        </div>
                        {detailRow('Party', row.party)}
                        {detailRow('Issued', dt(row.date))}
                        {detailRow('Due', dt(row.dueDate))}
                        {detailRow('Paid at', dt(row.paidAt))}
                    </div>

                    {/* billed trip facts */}
                    {(row.shipmentId || row.shipmentNumber) && (
                        <div className="rounded-md border px-3 py-2">
                            <p className="border-b pb-2 text-xs font-medium text-muted-foreground">
                                Billed shipment
                            </p>
                            <div className="pt-1">
                                {detailRow(
                                    'Shipment',
                                    row.shipmentNumber ?? row.shipmentId
                                )}
                                {row.lane && detailRow('Lane', row.lane)}
                                {row.partnershipId &&
                                    detailRow(
                                        'Partnership',
                                        `#${row.partnershipId}`
                                    )}
                            </div>
                        </div>
                    )}

                    {isFreight && (
                        <div className="rounded-md border px-3 py-2">
                            <p className="border-b pb-2 text-xs font-medium text-muted-foreground">
                                Fare breakdown
                            </p>
                            <div className="pt-1">
                                {detailRow(
                                    'Freight cost',
                                    fmtRaw(row.freightCost, row.currency)
                                )}
                                {detailRow(
                                    'Fuel surcharge',
                                    fmtRaw(row.fuelSurcharge, row.currency)
                                )}
                                {detailRow(
                                    'Accessorial',
                                    fmtRaw(row.accessorialCharges, row.currency)
                                )}
                                {detailRow(
                                    'Tax',
                                    fmtRaw(row.taxAmount, row.currency)
                                )}
                                <div className="mt-1 border-t pt-1">
                                    {detailRow(
                                        'Total',
                                        fmtRaw(row.amount, row.currency)
                                    )}
                                </div>
                                {row.pmsStatus &&
                                    detailRow('PMS status', row.pmsStatus)}
                            </div>
                        </div>
                    )}

                    {(isPayable || isSettlement) && row.paidAmount != null && (
                        <div className="rounded-md border px-3 py-2">
                            <p className="border-b pb-2 text-xs font-medium text-muted-foreground">
                                Settlement
                            </p>
                            <div className="pt-1">
                                {detailRow(
                                    'Paid',
                                    fmtRaw(row.paidAmount, row.currency)
                                )}
                                {detailRow(
                                    'Outstanding',
                                    fmtRaw(outstanding, row.currency)
                                )}
                            </div>
                        </div>
                    )}

                    {((isPayable && row.pmsReferenceId) ||
                        (isPayable && row.notes)) && (
                        <div className="rounded-md border px-3 py-2 text-sm">
                            {row.pmsReferenceId && (
                                <div className="grid grid-cols-[130px_minmax(0,1fr)] gap-2 py-1">
                                    <span className="text-muted-foreground">
                                        PMS reference
                                    </span>
                                    <span className="font-mono text-xs">
                                        {row.pmsReferenceId}
                                    </span>
                                </div>
                            )}
                            {row.notes && (
                                <div className="grid grid-cols-[130px_minmax(0,1fr)] gap-2 py-1">
                                    <span className="text-muted-foreground">
                                        Notes
                                    </span>
                                    <span className="font-medium">
                                        {row.notes}
                                    </span>
                                </div>
                            )}
                        </div>
                    )}

                    <div className="flex justify-end">
                        <Button variant="outline" size="sm" onClick={download}>
                            <Download className="mr-1 h-4 w-4" />
                            Download record
                        </Button>
                    </div>
                </DialogContent>
            </Dialog>
        </>
    );
}
